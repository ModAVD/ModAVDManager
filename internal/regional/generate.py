"""Regenerate CLDR's Windows to IANA world defaults. No SDK or network access is used."""

import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import xml.etree.ElementTree as ET

SOURCE = 'https://raw.githubusercontent.com/unicode-org/cldr/96e54b273d2da4ec6fbad350ba19ff23fa24a588/common/supplemental/windowsZones.xml'
SHA256 = '5f902f94106a396cb7774f0b0e1ca4dfecb686494045350c0b4935d378e3913b'

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('windows_zones', type=Path, help=SOURCE)
    args = parser.parse_args()
    data = args.windows_zones.read_bytes()
    if hashlib.sha256(data).hexdigest() != SHA256:
        raise SystemExit('input is not the pinned CLDR 49 windowsZones.xml')
    zones = {}
    for entry in ET.fromstring(data).iter('mapZone'):
        if entry.attrib['territory'] == '001':
            key, value = entry.attrib['other'], entry.attrib['type']
            assert key not in zones and '/' in value and ' ' not in value
            zones[key] = value
    assert zones['UTC'] == 'Etc/UTC' and zones['China Standard Time'] == 'Asia/Shanghai'
    output = Path(__file__).with_name('windows_zones.go')
    text = ('// Code generated by generate.py from CLDR 49; DO NOT EDIT.\n'
            '// Copyright 2001-2026 Unicode, Inc. Licensed under Unicode-3.0.\n'
            '// See UNICODE-LICENSE. World defaults, territory 001.\n'
            f'// Source: {SOURCE}\n'
            f'// SHA-256: {SHA256}\n\npackage regional\n\nvar windowsZones = map[string]string{{\n')
    for key, value in sorted(zones.items()):
        text += '\t' + json.dumps(key) + ': ' + json.dumps(value) + ',\n'
    text += '}\n'
    output.write_text(text, encoding='utf-8', newline='\n')
    subprocess.run(['gofmt', '-w', str(output)], check=True)
    print(f'{len(zones)} Windows time zones')

if __name__ == '__main__':
    main()
