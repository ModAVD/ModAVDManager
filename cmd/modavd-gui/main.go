func main() {
	// Hidden subcommands first, before any flag parsing or root lookup: emu and host re-run this executable as the
	// spawn helper of host.StartOrphan, as the Vulkan probe child and as the boot watch (same routing as internal/cli
	// Main).
	if len(os.Args) > 1 {
		switch os.Args[1] {
		case host.SpawnHelperArg:
			os.Exit(host.SpawnHelperMain(os.Args[2:], os.Stdout))
		case emu.VulkanProbeArg:
			os.Exit(emu.RunVulkanProbe(os.Stdout))
		case emu.BootWatchArg:
			os.Exit(emu.RunBootWatch(os.Args[2:], os.Stderr))
		case versionArg:
			os.Exit(printVersion())
		}
	}
	if exe, err := os.Executable(); err == nil {
		host.SetOrphanHelper(exe)
	}
	os.Exit(run(os.Args[1:]))
}

var usage = func() string {
	if runtime.GOOS == "darwin" && runtime.GOARCH == "arm64" {
		return "用法：ModAVD [--root 根目录] [--port 端口] [--no-window] [--chrome-window] [--dev]"
	}
	return "用法：ModAVD.exe [--root 根目录] [--port 端口] [--no-window] [--dev]"
}()

// flagValueNames are the placeholders the usage line gives the options that take a value.
var flagValueNames = map[string]string{"root": "根目录", "port": "端口"}

// helpText is what --help shows: the usage line, then every option with what it does.
func helpText(fs *flag.FlagSet) string {
	var b strings.Builder
	b.WriteString(usage + "\n")
	fs.VisitAll(func(f *flag.Flag) {
		name := "--" + f.Name
		if name == update.HandoffArg {
			return
		}
		if v := flagValueNames[f.Name]; v != "" {
			name += " " + v
		}
		fmt.Fprintf(&b, "\n%s：%s", name, f.Usage)
	})
	return b.String()
}

// versionArg is the hidden `ModAVD.exe __version`: one line on stdout, the same envelope as `modavd version --json`,
// no window, no server, no message box (for callers such as AUTO-MAS that need the manager's version without starting
// it). Every later version keeps it.
const versionArg = "__version"

func printVersion() int {
	b, err := json.Marshal(map[string]any{"ok": true, "data": map[string]any{
		"version": buildinfo.Version, "protocol": buildinfo.Protocol, "go": runtime.Version()}})
	if err != nil {
		return 1
	}
	if _, err := os.Stdout.Write(append(b, '\n')); err != nil {
		return 1
	}
	return 0
}

func run(args []string) (code int) {
	var log *logx.Logger
	defer func() {
		// A GUI process has no console: a panic would otherwise end it without a trace.
		if p := recover(); p != nil {
			log.Errorf("管理器崩溃: %v\n%s", p, debug.Stack())
			fatal(fmt.Sprintf("管理器出错退出了：%v", p))
			code = 1
		}
	}()

	fs := flag.NewFlagSet("ModAVD", flag.ContinueOnError)
	fs.SetOutput(io.Discard)
	rootFlag := fs.String("root", "", "ModAVD 根目录")
	port := fs.Int("port", 0, "监听端口（0 = 随机）")
	noWindow := fs.Bool("no-window", false, "不打开窗口")
	var chromeWindow bool
	if runtime.GOOS == "darwin" && runtime.GOARCH == "arm64" {
		fs.BoolVar(&chromeWindow, "chrome-window", false, "用独立 Chrome 应用窗口打开（默认使用系统浏览器）")
	}
	dev := fs.Bool("dev", false, "开发模式：提供 /dev/ 的模拟后端页面，没有窗口也不自动退出")
	handoffArg := fs.String(strings.TrimPrefix(update.HandoffArg, "--"), "", "更新交接 ID")
	if err := fs.Parse(args); err != nil {
		// --help / -h / -help ask for the usage: an information box and exit code 0, not an error (ModAVD/ModAVD#115).
		if errors.Is(err, flag.ErrHelp) {
			notice(helpText(fs))
			return 0
		}
		fatal("命令行参数不对：" + err.Error() + "\n\n" + usage)
		return 2
	}
	if fs.NArg() > 0 {
		fatal("多余的参数：" + strings.Join(fs.Args(), " ") + "\n\n" + usage)
		return 2
	}
	if *port < 0 || *port > 65535 {
		fatal(fmt.Sprintf("端口 %d 不对（0–65535，0 = 随机）", *port))
		return 2
	}
	var handoffID update.HandoffID
	if *handoffArg != "" {
		var err error
		handoffID, err = update.ParseHandoffID(*handoffArg)
		if err != nil {
			fatal(err.Error())
			return 2
		}
	}
	r, err := root.Resolve(*rootFlag)
	if err != nil {
		fatalErr("找不到 ModAVD 根目录", err)
		return errs.ExitCode(err)
	}

	minLevel := logx.Info
	if *dev {
		minLevel = logx.Debug
	}
	// Not closed by a defer: the crash handler above still writes to it, and the process exit closes it anyway.
	logFile := openLogFile(r.LogsDir())
	log = logx.New(logFile.sink(minLevel))

	releaseStart, updating, err := update.ManagerStart(r)
	if err != nil {
		fatalErr("检查更新交接失败", err)
		return errs.ExitCode(err)
	}
	if updating {
		log.Infof("%s", update.UpdatingMessage)
		if !*noWindow {
			if err := updatingNotice(); err != nil {
				log.Warnf("显示更新提示失败: %v", err)
			}
		}
		logFile.Close()
		return 0
	}
	inst, err := lockInstance(r)
	releaseStart()
	if err != nil {
		log.Errorf("%v", err)
		fatalErr("管理器启动失败", err)
		return 1
	}
	if inst == nil {
		return reopen(r, *noWindow, chromeWindow, log, handoffID)
	}
	defer inst.release()

	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()
	opt := ui.Options{
		Root:         r,
		Log:          log,
		Addr:         fmt.Sprintf("127.0.0.1:%d", *port),
		OpenWindow:   !*noWindow,
		ChromeWindow: chromeWindow,
		Dev:          *dev,
		HandoffID:    handoffID,
		// the tray icon and the boss keys (Windows): closing the window leaves the manager in the tray
		Tray: runtime.GOOS == "windows",
		Ready: func(baseURL, token string) {
			if err := inst.writeState(baseURL, token); err != nil {
				log.Warnf("写不了管理器状态文件（再次打开时找不到这个管理器）: %v", err)
			}
		},
	}
	if *dev {
		opt.IdleExit = -1
	}
	opt.Reopen = reopenArgs(r, *port, *noWindow, *dev, log)
	if err := ui.Run(ctx, opt); err != nil {
		log.Errorf("%v", err)
		// let go of the root first: the message box stays up until it is clicked away, and a new launch meanwhile
		// must not take this dead manager for a running one
		inst.release()
		fatalErr("管理器启动失败", err)
		return errs.ExitCode(err)
	}
	return 0
}

// reopenArgs is how the CLI starts this manager again after 设置 → 更新: this executable on the same root, with the
// options that change how it runs. Nil when the executable's path is unknown (更新 is then refused).
func reopenArgs(r *root.Root, port int, noWindow, dev bool, log *logx.Logger) *ui.Reopen {
	exe, err := os.Executable()
	if err != nil {
		log.Warnf("找不到管理器自己的路径，设置里不能更新: %v", err)
		return nil
	}
	args := []string{"--root", r.Dir}
	if port != 0 {
		args = append(args, "--port", strconv.Itoa(port))
	}
	if noWindow {
		args = append(args, "--no-window")
	}
	if dev {
		args = append(args, "--dev")
	}
	return &ui.Reopen{Exe: exe, Args: args}
}

// reopen is the second launch on a root: the running manager gets a new window.
func reopen(r *root.Root, noWindow, chromeWindow bool, log *logx.Logger, id update.HandoffID) int {
	if id != "" {
		// A failed delivery must not leave this result for a later launch.
		defer update.TakeHandoff(r, id, time.Now())
	}
	st, err := readStateWait(r, 5*time.Second)
	if err != nil {
		log.Errorf("已有管理器在运行，但读不到它的地址: %v", err)
		advice := "请关掉已经打开的管理器窗口，等十几秒后再打开；还不行就在任务管理器里结束 ModAVD.exe。"
		if runtime.GOOS == "darwin" {
			advice = "请关掉已经打开的管理器页面，等一分钟后再打开；还不行就在活动监视器里结束 ModAVD 管理器。"
		}
		fatal("这个根目录的 ModAVD 管理器已经在运行，但找不到它的地址。\n\n" + advice + "\n\n根目录：" + r.Dir)
		return 1
	}
	if id != "" {
		if err := forwardHandoff(st, id); err != nil {
			log.Warnf("把本次更新结果交给已运行的管理器失败: %v", err)
		}
	}
	if noWindow {
		return 0
	}
	log.Infof("管理器已在运行（%s），重新打开窗口", st.URL)
	launch := ui.LaunchWindow
	if chromeWindow {
		launch = ui.LaunchChromeWindow
	}
	if _, err := launch(st.URL + "?t=" + st.Token); err != nil {
		log.Errorf("打不开管理器窗口: %v", err)
		fatal("打不开管理器窗口：" + err.Error() + "\n\n可以在浏览器里打开 " + st.URL)
		return 1
	}
	return 0
}

func fatalErr(what string, err error) {
	e := errs.As(err)
	msg := what + "：\n\n" + e.Message
	if e.Advice != "" {
		msg += "\n\n" + e.Advice
	}
	fatal(msg)
}
