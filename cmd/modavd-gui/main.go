// ModAVD is the desktop manager of one root. It runs ui's local server and opens
// an Edge app window on Windows or the default browser on macOS (optionally Chrome
// app mode). On Windows it also puts an icon in the tray and registers the instances'
// boss keys; closing the page leaves it there until 退出 in the icon's menu. Elsewhere
// closing the page ends it after running jobs finish. A second launch on the same
// root reopens the page.
//
// --start <i> boots instance i with its window as soon as the manager is up (what the page's start button does), and
// --launch opens that app once it is up (for desktop shortcuts: boot and go straight into a game). When a manager of
// the root is running already, the request goes to it (POST /api/instances/{i}/start, the way a second launch hands
// over an update result) instead of starting a second server; the window is reopened as for any second launch, unless
// --no-window.
//
//	ModAVD.exe [--root <dir>] [--port N] [--no-window] [--dev] [--start <i> [--launch <package>[/<activity>]]]
//	ModAVD.exe __version      (hidden: version JSON on stdout, see versionArg)
//
// On Windows the usage (--help) and startup errors go to a redirected stdout / stderr, or else to the console of
// the parent (a terminal); only a launch with neither, such as a double click, shows a box (ModAVD/ModAVD#258).
//
// Build (GUI subsystem: no console window):
//
//	go build -trimpath -buildvcs=false -ldflags "-H=windowsgui" -o ModAVD.exe ./cmd/modavd-gui
//
// rsrc_windows_amd64.syso next to this file carries the icon, the manifest and the version information; it is
// generated by ./winres (see there), which writes tools\modavd.exe's next to the root main.go too. The icon
// (modavd.ico) is not covered by the code licence.
